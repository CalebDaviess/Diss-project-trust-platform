create table player_profile (
    profile_id varchar(128) primary key,
    global_trust_score integer not null default 100
);

create table game_connection (
    connection_id varchar(128) primary key,
    profile_id varchar(128) not null references player_profile(profile_id),
    operator_id varchar(128) not null,
    game_id varchar(128) not null
);

create index idx_game_connection_profile on game_connection(profile_id);

create table accountability_record (
    record_id varchar(36) primary key,
    connection_id varchar(128) not null unique references game_connection(connection_id),
    profile_id varchar(128) not null references player_profile(profile_id),
    operator_id varchar(128) not null,
    game_id varchar(128) not null,
    suspicion_score integer not null,
    status varchar(32) not null
);

create index idx_accountability_record_profile on accountability_record(profile_id);

create table case_event (
    event_id bigint generated by default as identity primary key,
    record_id varchar(36) not null references accountability_record(record_id),
    occurred_at timestamp with time zone not null,
    offence_type varchar(32) not null,
    score integer not null,
    evidence_link varchar(512),
    status varchar(32) not null
);

create index idx_case_event_record on case_event(record_id, occurred_at);

create table external_ban (
    ban_id varchar(128) primary key,
    profile_id varchar(128) not null references player_profile(profile_id),
    connection_id varchar(128) not null references game_connection(connection_id),
    operator_id varchar(128) not null,
    game_id varchar(128) not null,
    reason varchar(255),
    banned_at timestamp with time zone not null,
    expires_at timestamp with time zone,
    trust_delta integer not null default 0
);

create index idx_external_ban_profile_connection on external_ban(profile_id, connection_id);

