-- ── Conduct pivot ────────────────────────────────────────────────────────────
-- The platform's built/evaluated core is now CONDUCT detection (toxic chat/voice); cheating is
-- detected by EXTERNAL third-party anti-cheats and INGESTED as auto-confirmed, appealable verdicts.
-- This migration: (1) renames the record score to conduct_score, (2) source-attributes case
-- events, (3) adds an immutable audit trail, (4) persists ingested anti-cheat verdicts.

-- (1) The score on a record now reflects conduct detection, not cheat suspicion.
alter table accountability_record rename column suspicion_score to conduct_score;

-- (2) Every case event carries the authority that produced it (conduct engine / anti-cheat /
--     operator). Existing rows pre-date the pivot and came from the detection pipeline.
alter table case_event add column source varchar(32) not null default 'CONDUCT_ENGINE';

-- (3) Immutable, source-attributed audit trail — "who did what, when, why" for every state change.
create table audit_entry (
    entry_id bigint generated by default as identity primary key,
    record_id varchar(36) not null references accountability_record(record_id),
    occurred_at timestamp with time zone not null,
    source varchar(32) not null,
    actor varchar(256) not null,
    action varchar(64) not null,
    detail varchar(512)
);

create index idx_audit_entry_record on audit_entry(record_id, occurred_at);

-- (4) Persisted third-party anti-cheat verdicts (idempotency + audit; mirrors external_ban).
create table anti_cheat_verdict (
    verdict_id varchar(128) primary key,
    profile_id varchar(128) not null references player_profile(profile_id),
    connection_id varchar(128) not null references game_connection(connection_id),
    operator_id varchar(128) not null,
    game_id varchar(128) not null,
    offence_type varchar(32) not null,
    confidence double precision not null,
    evidence_link varchar(512),
    detected_at timestamp with time zone not null,
    trust_delta integer not null default 0
);

create index idx_anti_cheat_verdict_profile_connection on anti_cheat_verdict(profile_id, connection_id);

